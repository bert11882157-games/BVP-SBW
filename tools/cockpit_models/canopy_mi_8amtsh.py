def _slice(tri, z):
    d = tri[:, 2] - z
    pts = []
    for i in range(3):
        a, b = tri[i], tri[(i + 1) % 3]
        if d[i] * d[(i + 1) % 3] < 0:
            s = d[i] / (d[i] - d[(i + 1) % 3])
            pts.append(a + (b - a) * s)
        elif d[i] == 0:
            pts.append(a)
    return pts


