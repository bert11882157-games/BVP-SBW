def section(z, tris):
    """the half section (x >= 0) of the glazed volume at station z, from the sill up along the glass (and the pillars) to the ceiling and in to the
    centre line: the slice points of the panes, the sill and pillar lines and the ceiling, ordered by height"""
    pts = []
    for t in tris:
        T = np.array(t)
        if T[:, 2].min() <= z <= T[:, 2].max():
            for p in _slice(T, z):
                if p[0] > -0.02:
                    pts.append((max(0.0, float(p[0])), float(p[1])))
    for a, b in ((P305_TOP, P305_BOT), (P304_TOP, P304_BOT), (W1_TL, W1_BL)) + tuple(SILL_LINES):
        if min(a[2], b[2]) <= z <= max(a[2], b[2]) and a[2] != b[2]:
            f = (z - a[2]) / (b[2] - a[2])
            q = a + (b - a) * f
            pts.append((float(q[0]), float(q[1])))
    pts = [p for p in pts if p[1] >= 2.05]
    pts.sort(key=lambda p: (round(p[1], 3), -p[0]))
    out = []
    for p in pts:                                   # drop repeats
        if out and abs(p[0] - out[-1][0]) < 1e-4 and abs(p[1] - out[-1][1]) < 1e-4:
            continue
        out.append(p)
    out.insert(0, (out[0][0], out[0][1] - SILL_DROP))
    xt, yt = out[-1]
    if yt < CEIL_Y - 1e-3 and xt > 1e-3:
        out.append((xt, CEIL_Y))
    if out[-1][0] > 1e-3:
        out.append((0.0, out[-1][1]))
    return out


