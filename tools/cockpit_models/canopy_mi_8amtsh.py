def ear_clip(P):
    P = [np.array(p, float) for p in P]
    n = len(P)
    area = sum(P[i][0] * P[(i + 1) % n][1] - P[(i + 1) % n][0] * P[i][1] for i in range(n))
    idx = list(range(n)) if area > 0 else list(range(n))[::-1]
    out = []
    cr = lambda a, b, c: (b[0] - a[0]) * (c[1] - a[1]) - (b[1] - a[1]) * (c[0] - a[0])
    guard = 0
    while len(idx) > 3 and guard < 1000:
        guard += 1
        for k in range(len(idx)):
            i0, i1, i2 = idx[k - 1], idx[k], idx[(k + 1) % len(idx)]
            a, b, c = P[i0], P[i1], P[i2]
            if cr(a, b, c) <= 1e-12:
                continue
            if any(cr(a, b, P[j]) >= -1e-12 and cr(b, c, P[j]) >= -1e-12 and cr(c, a, P[j]) >= -1e-12 for j in idx if j not in (i0, i1, i2)):
                continue
            out.append((i0, i1, i2))
            idx.pop(k)
            break
    out.append(tuple(idx))
    return out


class Solids:
    """faces as a poly mesh in model pixels; every face has one winding, toward its normal"""

    def __init__(self):
        self.P, self.N, self.U, self.polys = [], [], [], []

    def face(self, pts, n, uv, double=False):
        for flip in ((False, True) if double else (False,)):
            pp = [np.array(q, float) for q in pts]
            nn = -np.array(n, float) if flip else np.array(n, float)
            if flip:
                pp = pp[::-1]
            px = [[float(q[0]) * 16, float(q[1]) * 16, -float(q[2]) * 16] for q in pp]
            npx = np.array([nn[0], nn[1], -nn[2]])
            a, b, c = (np.array(q) for q in px[:3])
            if np.cross(b - a, c - a) @ npx > 0:       # the mesh loader mirrors X: in file pixels a face winds clockwise seen from its front
                px = px[::-1]
            ni = len(self.N)
            self.N.append([round(float(x), 5) + 0.0 for x in -npx])
            ui = len(self.U)
            self.U.append(list(uv))
            poly = []
            for p in px:
                poly.append([len(self.P), ni, ui])
                self.P.append([round(x, 4) + 0.0 for x in p])
            self.polys.append(poly)

    def quad(self, pts, n, uv, double=False):
        self.face(pts, n, uv, double)

    def obox(self, c, axes, half, uv):
        c = np.array(c, float)
        A = [unit(a) for a in axes]
        for k in range(3):
            for s in (-1, 1):
                i, j = [m for m in range(3) if m != k]
                fc = c + A[k] * half[k] * s
                q = [fc + A[i] * half[i] * a + A[j] * half[j] * b for a, b in ((-1, -1), (1, -1), (1, 1), (-1, 1))]
                n = np.cross(q[1] - q[0], q[2] - q[0])
                n = n / np.linalg.norm(n)
                if n @ (fc - c) < 0:
                    n = -n
                self.face(q, n, uv)

    def beam(self, a, b, w, t, uv, up=(0, 1, 0), ext=0.0):
        a, b = np.array(a, float), np.array(b, float)
        u = unit(b - a)
        v = np.array(up, float)
        v = v - (v @ u) * u
        if np.linalg.norm(v) < 1e-6:
            v = np.array([1.0, 0, 0]) - u[0] * u
        v = unit(v)
        s = unit(np.cross(u, v))
        self.obox((a + b) / 2, (u, v, s), (np.linalg.norm(b - a) / 2 + ext, w / 2, t / 2), uv)

    def mesh(self):
        return {'normalized_uvs': True, 'positions': self.P, 'normals': self.N, 'uvs': self.U, 'polys': self.polys}


def hull_xyz(pm):
    return np.array(pm['positions'], float) * np.array([1, 1, -1]) / 16.0


def find_faces(pm, P, quads, tol=0.0025):
    """indices of the hull polys whose corners are the given quads' corners (one match per quad)"""
    cents = np.array([P[[v[0] for v in poly]].mean(0) if poly else [9e9] * 3 for poly in pm['polys']])
    out = []
    for q in quads:
        q = np.array(q, float)
        cand = np.where(np.abs(cents - q.mean(0)).max(1) < tol)[0]
        for k in cand:
            V = P[[v[0] for v in pm['polys'][k]]]
            if len(V) == len(q) and all(np.abs(V - c).max(1).min() < tol for c in q):
                out.append(int(k))
                break
        else:
            out.append(None)
    return out


def face_uv(pm, k):
    U = np.array(pm['uvs'], float)
    return [float(v) for v in U[[v[2] for v in pm['polys'][k]]].mean(0)]


def ring(solids, outer, inner, n, uv):
    """the four trapezoids between a quad and the quad inside it (corresponding corners), facing n"""
    for i in range(4):
        solids.quad([outer[i], outer[(i + 1) % 4], inner[(i + 1) % 4], inner[i]], n, uv)


def build_roof_window(solids, pm, P, sign, skin_uv):
    """the eyebrow window of one side: removes plate A and the ceiling plate U, puts the frame ring, the ceiling ring, the left-over ceiling
    piece and the shaft in. Returns (removed face ids, the pane triangles)"""
    A_ = [np.array([sign * p[0], p[1], p[2]]) for p in ROOF_A]
    U_ = [np.array([sign * p[0], p[1], p[2]]) for p in ROOF_U]
    H_ = [np.array([sign * p[0], p[1], p[2]]) for p in ROOF_HDR]
    ka, ku, kh = find_faces(pm, P, [A_, U_, H_])
    if ka is None or ku is None or kh is None:
        return None
    nA = unit(np.cross(A_[1] - A_[0], A_[3] - A_[0]))
    if nA[1] < 0:
        nA = -nA
    Ai = inset_quad(A_, ROOF_M)
    # the footprint of A on the ceiling plate: its corners dropped onto U's plane; U = the left-over piece + the footprint quad
    cU = np.mean(U_, 0)
    nU = unit(np.cross(U_[1] - U_[0], U_[2] - U_[0]))
    if nU[1] > 0:
        nU = -nU

    def drop(p):
        p = np.array(p, float)
        # vertical projection onto U's plane
        y = U_[0][1] + (-(nU[0] * (p[0] - U_[0][0]) + nU[2] * (p[2] - U_[0][2])) / nU[1])
        return np.array([p[0], y, p[2]])
    Ad = [drop(p) for p in A_]
    Hi = [drop(p) for p in Ai]
    uv_ceil = skin_uv
    ring(solids, A_, Ai, nA, skin_uv)                                    # the frame ring on the roof plate
    solids.quad([U_[0], U_[1], Ad[1], Ad[0]], nU, uv_ceil, double=False)   # the ceiling piece left of the footprint
    ring(solids, Ad, Hi, nU, uv_ceil)                                    # the ceiling ring round the hole
    for i in range(4):                                                   # the shaft: from the hole up to the pane, facing in
        a0, a1, h0, h1 = Ai[i], Ai[(i + 1) % 4], Hi[i], Hi[(i + 1) % 4]
        mid = (a0 + a1 + h0 + h1) / 4
        cen = (np.mean(Ai, 0) + np.mean(Hi, 0)) / 2
        e = unit(a1 - a0)
        nn = unit(np.cross(e, a0 - h0))
        if nn @ (cen - mid) < 0:
            nn = -nn
        solids.quad([a0, a1, h1, h0], nn, uv_ceil)
    return [ka, ku, kh], quad_tris(Ai)


def cut_interior(pm, P):
    box = np.array(CUT_BOXES, float)
    lo, hi = box[:, :3] - CUT_TOL, box[:, 3:] + CUT_TOL
    kb = np.array(KEEP_BOXES, float)
    klo, khi = kb[:, :3] - CUT_TOL, kb[:, 3:] + CUT_TOL
    ex = np.array(EXTRA_CUT, float)
    idx = set()
    for k, poly in enumerate(pm['polys']):
        if not poly:
            continue
        V = P[[v[0] for v in poly]]
        vl, vh = V.min(0), V.max(0)
        if np.any(np.all(vl >= lo, axis=1) & np.all(vh <= hi, axis=1)) and \
                not np.any(np.all(vl >= klo, axis=1) & np.all(vh <= khi, axis=1)):
            idx.add(k)
        elif len(ex) and np.abs(ex - V.mean(0)).max(1).min() < EXTRA_TOL:
            idx.add(k)
    return idx


