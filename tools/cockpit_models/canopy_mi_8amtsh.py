def build(pm, hull_P, sw):
    """edits the hull poly mesh and returns (the new solids, glass triangles, counts)"""
    cut = cut_interior(pm, hull_P)
    skin_k = None
    solids = Solids()
    removed = set(cut)
    glass = []
    skin_uv = None
    for sign in (1, -1):
        A_ = [np.array([sign * p[0], p[1], p[2]]) for p in ROOF_A]
        ka = find_faces(pm, hull_P, [A_])[0]
        if ka is not None and skin_uv is None:
            skin_uv = face_uv(pm, ka)
    n_roof = 0
    for sign in (1, -1):
        r = build_roof_window(solids, pm, hull_P, sign, skin_uv)
        if r is not None:
            removed |= set(r[0])
            n_roof += 1
    n_chin = 0
    for sign in (1, -1):
        for outer, inner in CHIN:
            quads = [[np.array([sign * p[0], p[1], p[2]]) for p in q] for q in (outer, inner)]
            ks = find_faces(pm, hull_P, quads)
            if None not in ks:
                removed |= set(ks)
                n_chin += 1
    return removed, solids, (len(cut), n_roof, n_chin)


NOSE_EDGE = [(0.0, 2.392, 7.471), (0.422, 2.392, 7.471), (0.797, 2.298, 7.284)]     # the nose block's rear top edge (elements 301 / 310)


def nose_flashing(solids, uv):
    """the strip between the windscreen's lower edge and the nose block behind it (the glass leans back, the block stands further forward), closed
    so the nose bay cannot be seen into; one winding up, both sides"""
    quad = windscreen_pane()[0]
    for sign in (1, -1):
        B = np.array([sign * 0.0, quad[3][1], quad[3][2]])
        D = np.array([sign * quad[2][0], quad[2][1], quad[2][2]])
        pts = [B] + [np.array([sign * x, y, z]) for x, y, z in NOSE_EDGE[1:]] + [D]
        pts = [q - np.array([0.0, 0.004, 0.0]) for q in pts]          # 4 mm under the block's top edge: no coplanar overlap with it
        solids.face(pts if sign > 0 else pts[::-1], (0.0, 1.0, 0.15), uv, double=True)


def post_and_wipers(solids, uv_dark):
    """the slim centre post and a wiper for each windscreen pane"""
    solids.beam(POST_TOP + [0, 0.012, 0.0], POST_BOT - [0, 0.0, 0.0], 0.047, 0.060, uv_dark, up=(1, 0, 0), ext=0.012)
    c, n = windscreen_pane()[1]
    if n[2] < 0:
        n = -n
    quad = windscreen_pane()[0]
    # the wiper: a blade lying on the glass near the pane's foot, an arm to its pivot on the pane's inner-bottom corner
    bl, br = quad[3], quad[2]                     # POST_BOT side, pillar side (bottom edge)
    up = unit(quad[0] - quad[3])
    along = unit(br - bl)
    off = n * 0.012
    for sgn in (1, -1):
        piv = bl + along * 0.10 + up * 0.035
        tip = bl + along * 0.62 + up * 0.17
        pv, tp = piv + off, tip + off
        if sgn < 0:
            pv, tp = mir(pv), mir(tp)
        solids.beam(pv, tp, 0.012, 0.010, uv_dark, up=(n[0] * sgn, n[1], n[2]))


def skin_uv_of(pm, P):
    ka = find_faces(pm, P, [[np.array(p) for p in ROOF_A]])[0]
    return face_uv(pm, ka) if ka is not None else [0.5, 0.5]


